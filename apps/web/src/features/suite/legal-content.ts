/** 文書の一覧（種類ごと）。 */
export const LEGAL_DOCUMENTS: Readonly<Record<LegalDocumentKey, LegalDocument>> = {
  terms: TERMS,
  privacy: PRIVACY,
};

/** 文の中の、運営者が埋める所（〈 〉）を見つける形。 */
export const PLACEHOLDER_PATTERN = /〈[^〈〉]+〉/g;

/**
 * 文書のすべての文（前書き・見出し・中身・最後の行）。
 * @param doc 文書
 * @returns 文の並び
 */
export function legalTexts(doc: LegalDocument): string[] {
  const texts = [doc.title, doc.lead, ...doc.intro, doc.closing];
  for (const section of doc.sections) {
    texts.push(section.heading);
    for (const block of section.blocks) {
      if (block.kind === "paragraph") texts.push(block.text);
      else if (block.kind === "list") texts.push(...block.items);
      else texts.push(...block.columns, ...block.rows.flat());
    }
  }
  return texts;
}

/**
 * 文書の中の、運営者が埋める所（〈 〉）。出てくる順で、重ねない。
 * @param doc 文書
 * @returns 埋める所の並び
 */
export function legalPlaceholders(doc: LegalDocument): string[] {
  return [...new Set(legalTexts(doc).flatMap((text) => text.match(PLACEHOLDER_PATTERN) ?? []))];
}
