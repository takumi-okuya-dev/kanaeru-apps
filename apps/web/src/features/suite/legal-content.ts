export const LEGAL_TEXT_IS_DRAFT = true;

/**
 * 本文のまとまり。文の中の〈 〉は運営者が埋める所、{{terms}}・{{privacy}} はもう一方のページへのリンク。
 * - paragraph：段落
 * - list：箇条書き（ordered なら番号つき）
 * - table：2つの列の表（狭い画面でも横に動かないよう、ページでは見出しと中身の並びで出す）
 */
export type LegalBlock =
  | { kind: "paragraph"; text: string }
  | { kind: "list"; items: readonly string[]; ordered?: boolean }
  | {
      kind: "table";
      columns: readonly [string, string];
      rows: readonly (readonly [string, string])[];
    };

/** 節（見出しの番号はページと写しが前から振る）。 */
export type LegalSection = {
  /** ページの中の印（#の後ろ。英小文字とハイフン） */
  id: string;
  /** 見出し（番号なし） */
  heading: string;
  /** 中身 */
  blocks: readonly LegalBlock[];
};

